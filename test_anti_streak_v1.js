'use strict';
const assert=require('node:assert/strict'),{make}=require('./test_pf_primary_runtime');
(async()=>{
  const {api}=await make({query:true});
  const config=api.getCardcountProfile().anti_streak_v1;
  const test=(seq,candidate,edge,base=.010)=>api.antiStreakQualification(seq.split(','),candidate,edge,base,config);
  assert.equal(api.roadPrimaryConfig(),null);
  assert(api.pfPrimaryConfig()?.enabled,'PF primary must be enabled by default');
  assert.equal(api.profileValue('decision_alpha',1),.28);
  assert.equal(api.profileValue('pf_max',70),.30);
  assert.equal(api.getCardcountProfile().pf_weight_smoothing_v1.reference_smoothing.max_delta,.004);
  assert.equal(api.currentRun('P,P,P'.split(',')).length,3);
  let r=test('P,P,P','B',.020);
  assert(r.opposite_blocked&&r.extra_ev_required===.012);
  assert.equal(r.required_ev,.022);
  assert.equal(r.current_run_side,'P');
  r=test('P,P,P,P,P','B',.030);
  assert(r.opposite_blocked&&r.extra_ev_required===.032);
  assert.equal(r.required_ev,.042);
  assert.equal(test('P,P,P,P,P','B',.043).opposite_blocked,false);
  assert(test('B,B,B','P',.020).opposite_blocked);
  assert.equal(test('P,P,T,P,P','B',.020).current_run_length,2);
  assert.equal(test('P,P,T,P,P','B',.020).opposite_blocked,false);
  assert.equal(test('P,P,T,P,P','B',.020,.010).extra_ev_required,0);
  const ignoreT={...config,count_ties_break_run:false};
  assert.equal(api.antiStreakQualification('P,P,T,P,P'.split(','),'B',.01,.01,ignoreT).current_run_length,4);
  r=test('P,P,P','P',.015);
  assert.equal(r.same_side_ev_relief,.003);
  assert(!r.opposite_blocked);
  assert.equal(test('P,P,P','B',.020,.010).required_ev,.022);
  assert.equal(api.antiStreakQualification(['P','P','P'],'B',.02,.01,{...config,enabled:false}).opposite_blocked,false);
  const history=['P','P','P','P','P'],pred=api.applyFinalPrediction(history);
  assert.equal(pred.finalProbability.mode,'pf_primary');
  assert.equal(pred.current_run_side,'P');
  assert.equal(pred.current_run_length,5);
  assert.equal(pred.finalProbability.anti_streak_enabled,true);
  assert.equal(pred.finalProbability.current_run_length,5);
  assert(pred.finalProbability.execution_order.includes('anti_streak_qualification'));
  assert.equal(pred.finalProbability.anti_streak.opposite_blocked,pred.opposite_blocked);
  if(pred.opposite_blocked)assert.equal(pred.bet_direction,'Skip');
  api.registerPrediction(history,pred);api.settlePending('B',null,history);
  const exported=JSON.parse(api.exportTrainingData()).rows.at(-1);
  assert.equal(exported.current_run_length,5);
  assert.equal(exported.anti_streak_enabled,true);
  console.log('PASS: anti-streak run/tie logic, 3/5 EV premiums, both directions, independent bet eligibility, PF primary, export and rollback switch');
})().catch(e=>{console.error(e);process.exitCode=1});
