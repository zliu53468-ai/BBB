"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm");
const legacy=require("./bayes_markov_runtime");
const E=legacy.BBBQuantEngine;
assert.equal(typeof legacy.estimate,"function");
assert.equal(typeof E,"function");
const empty=new E(),p0=empty.predictNext();
assert.equal(p0.direction,"Skip");
assert.equal(p0.bet_fraction,0);
assert.equal(p0.count_source,"estimated");
assert.equal(empty.generateShoeContext().length,128);
assert.equal(empty.generateShoeContext()[0],0);
assert.throws(()=>empty.updateRound("X"),/outcome/);
assert.throws(()=>empty.updateRound("B",{cards:[1,2]}),/cards/);
assert.throws(()=>empty.injectShoeContext(Array(256).fill(0)),/incompatible/);
let m=new E();
m.updateRound("B");m.updateRound("P");m.updateRound("T");
assert.equal(m.estimatedRounds,3);
assert.equal(m.predictNext().bet_fraction,0);
assert.equal(m.predictNext().count_source,"estimated");
assert(Math.abs(Object.values(m.counts).reduce((a,b)=>a+b,0)-m.remainingCards)<1e-8);
assert(Math.abs(Object.values(m.cardDensities).reduce((a,b)=>a+b,0)-1)<1e-10);
assert(Object.values(m.counts).every(x=>x>=0));
assert.equal(m.generateShoeContext().length,128);
assert(m.generateShoeContext().every(Number.isFinite));
assert.equal(m.generateShoeContext()[0],m.trueCount**2*Math.sign(m.trueCount));
const q=new E();
for(let i=0;i<8;i++)q.updateRound("B",{cards:[1,2,3,4,1,2],bankerPair:false,playerPair:i%2===0,luckySix:false});
assert.equal(q.countSource,"observed");
assert(q.trueCount>2);
assert.equal(q.cardRatios.low,(128-48)/128);
const p=q.predictNext();
assert(Math.abs(p.count_weight-Math.min(.7,Math.abs(q.trueCount)*.15))<1e-12);
assert(Math.abs(p.probabilities.B-(p.baseline_probabilities.B*(1-p.count_weight)+p.count_probability.B*p.count_weight))<1e-12);
assert(Math.abs(Object.values(p.probabilities).reduce((a,b)=>a+b,0)-1)<1e-12);
assert.equal(p.direction,"B");
assert(p.ev_banker>.005);
assert(p.bet_fraction>=.05&&p.bet_fraction<=.30);
assert(p.side_bets.player_pair.observed_rounds===8);
assert.equal(p.side_bet_stake_fraction,0);
assert.deepEqual(q.generateShoeContext().length,128);
const context=Array.from({length:256},(_,i)=>i/255);
const injected=q.injectShoeContext(context,{experimental:true});
assert.deepEqual(injected.slice(128),context.slice(128));
assert.equal(injected[0],q.trueCount**2*Math.sign(q.trueCount));
assert.deepEqual(E.fromHistory(["B","P","T"]).generateShoeContext(),m.generateShoeContext());
const kp=E.fractionalKelly(.51,.49,1);
assert.equal(kp.bet_fraction,.05);
assert(kp.minimum_clip_applied);
assert.equal(E.fractionalKelly(.4,.5,1).bet_fraction,0);
function panel(file,enabled){
  const sandbox={URLSearchParams,console};
  sandbox.window={location:{search:enabled?"?quant256=1":""},BBBQuantEngine:E};
  vm.runInNewContext(fs.readFileSync(file,"utf8"),sandbox,{filename:file});
  return sandbox.window.__BGS256_TEST__;
}
const seq="BPPBTBBPPTBBPPBTBPBPPBP".split("");
for(const file of ["app256.js","app256forward.js"]){
  const baseline=panel(file,false),quant=panel(file,true);
  const a=baseline.context256(seq),b=quant.context256(seq);
  assert.equal(a.vector.length,256);
  assert.equal(b.vector.length,256);
  assert.deepEqual(Array.from(b.vector.slice(128)),Array.from(a.vector.slice(128)),"last 128 road slots must remain unchanged");
  assert.deepEqual(Array.from(b.vector.slice(0,128)),E.fromHistory(seq).generateShoeContext());
  assert.equal(b.feature_schema,"BBB_QUANT_128_V2");
  assert.equal(quant.choose(seq).direction,"Skip","B/P/T alone must never produce a fake observed TC");
  assert(["B","P"].includes(baseline.choose(seq).direction));
}
console.log("PASS quant V2: legacy API, observed/estimated separation, EV/TC gates, Kelly, 128D signed TC², conservation, 256D road slice and no default production changes");
